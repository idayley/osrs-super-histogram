package com.superhistogram.model.skill;

import static org.junit.Assert.assertEquals;

import java.io.File;
import java.lang.reflect.Field;
import java.lang.reflect.Modifier;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.List;
import java.util.function.Predicate;
import net.runelite.api.gameval.ItemID;
import net.runelite.api.gameval.ObjectID;
import org.junit.Test;

/**
 * The Plugin Hub forbids reflection, so {@link GameIds} lists its ids by name. This test keeps it in step with
 * RuneLite: it finds every id by its name pattern and checks GameIds.java is exactly what those rules give. When a
 * RuneLite update adds an id, it fails and writes the regenerated file to build/GameIds.java to copy over.
 */
public class GameIdsTest
{
	private static final String PATH = "src/main/java/com/superhistogram/model/skill/GameIds.java";

	private static List<String> names(Class<?> table, Predicate<String> rule)
	{
		List<String> out = new ArrayList<>();
		for (Field f : table.getFields())
		{
			if (Modifier.isStatic(f.getModifiers()) && f.getType() == int.class && rule.test(f.getName()))
			{
				out.add(f.getName());
			}
		}
		out.sort(null);
		return out;
	}

	private static boolean trap(String n)
	{
		return n.startsWith("HUNTING_") && (n.contains("BOXTRAP") || n.contains("OJIBWAY") || n.contains("SNARE")
			|| n.contains("DEADFALL") || n.contains("IMPTRAP") || n.contains("MONKEYTRAP"));
	}

	private static boolean trapCaught(String n)
	{
		return trap(n) && (n.contains("_FULL") || n.contains("SNARE_RABBIT") || n.contains("FOR_TAKING"));
	}

	private static boolean trapDown(String n)
	{
		return trap(n) && !trapCaught(n) && (n.contains("FAILED") || n.contains("BROKEN"));
	}

	private static boolean trapSet(String n)
	{
		return trap(n) && !trapCaught(n) && !trapDown(n) && !n.contains("UNSET") && !n.contains("CHECKING");
	}

	private static void set(StringBuilder b, String doc, String name, String table, List<String> ids)
	{
		b.append("\t/** ").append(doc).append(" */\n");
		b.append("\tstatic final Set<Integer> ").append(name).append(" = of(");
		for (int i = 0; i < ids.size(); i++)
		{
			b.append(i % 3 == 0 ? "\n\t\t" : " ").append(table).append('.').append(ids.get(i));
			b.append(i < ids.size() - 1 ? "," : "");
		}
		b.append(");\n\n");
	}

	static String source()
	{
		StringBuilder b = new StringBuilder();
		b.append("package com.superhistogram.model.skill;\n\n");
		b.append("import java.util.Arrays;\nimport java.util.Collections;\nimport java.util.HashSet;\nimport java.util.Set;\n");
		b.append("import net.runelite.api.gameval.ItemID;\nimport net.runelite.api.gameval.ObjectID;\n\n");
		b.append("/**\n * Item and object ids the bar watches for, by name. Generated by GameIdsTest from RuneLite's id tables;\n");
		b.append(" * don't edit by hand. When RuneLite adds an id the test fails and writes the new file to build/GameIds.java.\n */\n");
		b.append("final class GameIds\n{\n\tprivate GameIds()\n\t{\n\t}\n\n");
		set(b, "Essence you carry to an altar (not Guardians of the Rift's).", "ESSENCE", "ItemID",
			names(ItemID.class, n -> !n.startsWith("GOTR_") && (n.startsWith("BLANKRUNE") || n.endsWith("_ESSENCE")
				&& !n.startsWith("BLOOD_") || n.startsWith("ARCEUUS_ESSENCE_BLOCK") || n.equals("BIGBLANKRUNE"))));
		set(b, "Bird houses in every state.", "BIRDHOUSES", "ObjectID",
			names(ObjectID.class, n -> n.startsWith("BIRDHOUSE_")));
		set(b, "Runes (and coins) a spell uses up.", "RUNES", "ItemID",
			names(ItemID.class, n -> n.matches("[A-Z]+RUNE") || n.equals("COINS")));
		set(b, "Coin pouches from pickpocketing.", "POUCHES", "ItemID",
			names(ItemID.class, n -> n.startsWith("PICKPOCKET_COIN_POUCH")));
		set(b, "Salvage pulled from shipwrecks.", "SALVAGE", "ItemID",
			names(ItemID.class, n -> n.endsWith("SHIPWRECK_SALVAGE")));
		set(b, "Hunter traps that are set and waiting.", "TRAP_SET", "ObjectID",
			names(ObjectID.class, GameIdsTest::trapSet));
		set(b, "Hunter traps holding a catch.", "TRAP_CAUGHT", "ObjectID",
			names(ObjectID.class, GameIdsTest::trapCaught));
		set(b, "Hunter traps that failed or collapsed.", "TRAP_DOWN", "ObjectID",
			names(ObjectID.class, GameIdsTest::trapDown));
		b.append("\tprivate static Set<Integer> of(Integer... ids)\n\t{\n");
		b.append("\t\treturn Collections.unmodifiableSet(new HashSet<>(Arrays.asList(ids)));\n\t}\n}\n");
		return b.toString();
	}

	@Test
	public void gameIdsMatchRuneLitesTables() throws Exception
	{
		String want = source();
		File file = new File(PATH);
		String have = file.exists() ? new String(Files.readAllBytes(file.toPath()), StandardCharsets.UTF_8) : "";
		if (!want.equals(have))
		{
			File out = new File("build/GameIds.java");
			out.getParentFile().mkdirs();
			Files.write(out.toPath(), want.getBytes(StandardCharsets.UTF_8));
		}
		assertEquals("RuneLite's ids changed: copy build/GameIds.java over " + PATH, want, have);
	}
}
